######################################### SHANNON INDEX

yield_data = final_df[final_df['Element'] == 'Area harvested']


# List of year columns
year_columns = ['Y' + str(year) for year in range(1992, 2022)]

# Group the data by country ('Alpha-3code') and item, and sum values across the years
grouped_data = yield_data.groupby(['Alpha-3code', 'Item'])[year_columns].sum()

# Function to calculate the Shannon Index for a group
def shannon_index(group):
    total = group.sum()  # Calculate the total sum of the group
    proportions = group / total  # Calculate the proportions of each value
    proportions = proportions[proportions > 0]  # Filter out zero proportions
    return -np.sum(proportions * np.log(proportions))  # Calculate the Shannon Index

# Calculate the Shannon Index for each country and year (grouped by 'Alpha-3code' and 'Item')
shannon_indices = grouped_data.groupby('Alpha-3code').apply(lambda x: x.apply(shannon_index))

# Calculate the average Shannon Index across years for each country
shannon_avg = shannon_indices[year_columns].mean(axis=1).to_frame(name='shannon_avg_item_all')
shannon_avg = shannon_avg.reset_index()

# Merge the average Shannon Index for items into the final DataFrame
final_df = final_df.merge(shannon_avg, on='Alpha-3code', how='left')

# Group the data by country ('Alpha-3code') and item group, and sum values across the years
grouped_data = yield_data.groupby(['Alpha-3code', 'item_group'])[year_columns].sum()

# Function to calculate the Shannon Index for a group (same function as above)
def shannon_index(group):
    total = group.sum()  # Calculate the total sum of the group
    proportions = group / total  # Calculate the proportions of each value
    proportions = proportions[proportions > 0]  # Filter out zero proportions
    return -np.sum(proportions * np.log(proportions))  # Calculate the Shannon Index

# Calculate the Shannon Index for each country and year (grouped by 'Alpha-3code' and 'item_group')
shannon_indices = grouped_data.groupby('Alpha-3code').apply(lambda x: x.apply(shannon_index))

# Calculate the average Shannon Index across years for each country (for item groups)
shannon_avg = shannon_indices[year_columns].mean(axis=1).to_frame(name='shannon_avg_itemgroup_all')
shannon_avg = shannon_avg.reset_index()

# Merge the average Shannon Index for item groups into the final DataFrame
final_df = final_df.merge(shannon_avg, on='Alpha-3code', how='left')

# Final DataFrame with Shannon Index for items and item groups added

final_df = final_df.reset_index()[['Area', 'Area Code (M49)', 'Alpha-2code', 'Alpha-3code', 'shannon_avg_item_all','shannon_avg_itemgroup_all' ]]
final_df = final_df.drop_duplicates(subset='Area', keep='first')
