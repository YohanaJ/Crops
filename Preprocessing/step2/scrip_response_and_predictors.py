filtered_data = pd.read_csv(data_path, encoding='latin1')

# Define columns for years (1992-2021) and their corresponding flags
year_columns = [f'Y{year}' for year in range(1992, 2022)]
flag_columns = [f'Y{year}F' for year in range(1992, 2022)]

# Select only relevant columns: area, area code, item, element, and year/flag columns
filtered_data = filtered_data[['Area', 'Area Code (M49)', 'Item', 'Element'] + year_columns + flag_columns]

# Load the table of item groups to filter only crop-related items
item_groups = pd.read_csv('/content/drive/MyDrive/ColabNotebooks/input/FAOSTAT_data_9-14-2023.csv')

# Define the desired crop groups to include in the analysis
desired_groups = [
    "Cereals, primary", "Fruit Primary", "Vegetables Primary",
    "Pulses, Total", "Oilcrops Primary", "Sugar Crops Primary", "Roots and Tubers, Total"
]

# Filter items that belong to the desired groups or are specifically "Other stimulant, spice and aromatic crops, n.e.c."
filtered_items = item_groups[
    (item_groups['Item Group'].isin(desired_groups)) |
    (item_groups['Item'] == "Other stimulant, spice and aromatic crops, n.e.c.")
]

# Exclude items whose name matches the name of the group (to avoid duplicates or aggregation errors)
filtered_items = filtered_items[filtered_items['Item'] != filtered_items['Item Group']]

# Filter the main dataset to include only rows where the item is in the filtered items list
filtered_data = filtered_data[filtered_data['Item'].isin(filtered_items['Item'])]

# 1. Filter the dataset to include only rows where "Element" is "Area harvested"
yield_data = filtered_data[filtered_data['Element'] == 'Area harvested']

# 2. Group the data by country and check if there is any data (non-NA) for all years in the range
valid_countries = yield_data.groupby('Area').apply(lambda group: all(group[year_columns].notna().any())).reset_index()
valid_countries.columns = ['Area', 'Valid']

# 3. Filter the dataset to include only countries with valid data for all years in the specified range
valid_countries_list = valid_countries[valid_countries['Valid']]['Area'].tolist()
filtered_data = filtered_data[filtered_data['Area'].isin(valid_countries_list)]

# Create a table of unique items and their associated groups
filtered_items = item_groups[['Item', 'Item Group']].drop_duplicates()

# Merge the item group information into the filtered data
filtered_data = filtered_data.merge(filtered_items, on='Item', how='left')

# Rename the 'Item Group' column to 'item_group' for clarity
filtered_data = filtered_data.rename(columns={'Item Group': 'item_group'})

