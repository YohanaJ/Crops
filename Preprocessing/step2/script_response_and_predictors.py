# Function to calculate the relative trend for each land cover class
def calculate_relative_trend(df):
    trends = {}
    for column in land_cover_columns:
        # Get the base value (1992) and end value (latest year) for the column
        base_value = df[df['Year'] == 1992][column].values[0]
        end_value = df[df['Year'] == df['Year'].max()][column].values[0]
        # Calculate the relative trend as the ratio of end value to base value
        trends[column + '_Trend'] = end_value / base_value
    return pd.Series(trends)

# Calculate the relative trend for each land cover class for each country
relative_trend_df = merged_df.groupby('Area Code (M49)').apply(calculate_relative_trend).reset_index()

