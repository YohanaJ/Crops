# Function to calculate the relative trend of yield gap for each group (country)
def calculate_relative_trend(group):
    # Ensure the data is sorted by year
    group = group.sort_values(by='Year')

    # Reshape the year column to fit the scikit-learn model
    X = group['Year'].values.reshape(-1, 1)
    y = group['AverageWeightedYieldGap'].values

    # Fit the linear regression model to calculate the trend (slope)
    model.fit(X, y)
    trend = model.coef_[0]

    # Retrieve the first value of 'AverageWeightedYieldGap', use 0.1 to avoid division by zero if the value is 0
    first_value = y[0] if y[0] != 0 else 0.1

    # Calculate the relative trend as the slope divided by the first value
    relative_trend = trend / first_value

    # Return a series with the calculated metrics
    return pd.Series({
        'Relative_yield_gap_trend': relative_trend,    # Relative yield gap trend
    })

# Apply the trend calculation function to each group (grouped by 'Alpha-3code')
relative_trends = yield_gap.groupby('Alpha-3code').apply(calculate_relative_trend).reset_index()

